import type { Prisma, PrismaClient, SecurityCheckType, SeoCheckType } from '@whc/db';
import { classifyDraft, type IssueDraft } from './issues';
import type { FileStorage } from './storage';

/** Saves an image file and its Screenshot row. Returns the row ID. */
export async function saveScreenshot(
  prisma: PrismaClient,
  storage: FileStorage,
  values: {
    scanId: string;
    scanPageId: string | null;
    kind: 'PAGE_FULL' | 'VIEWPORT' | 'ISSUE_CROP' | 'VISUAL_CURRENT' | 'VISUAL_DIFF';
    viewport: string;
    key: string;
    buffer: Buffer;
    width: number;
    height: number;
  },
): Promise<string> {
  await storage.put(values.key, values.buffer);
  const row = await prisma.screenshot.create({
    data: {
      scanId: values.scanId,
      scanPageId: values.scanPageId,
      kind: values.kind,
      viewport: values.viewport,
      storageKey: values.key,
      mimeType: values.key.endsWith('.png') ? 'image/png' : 'image/jpeg',
      width: values.width,
      height: values.height,
      sizeBytes: values.buffer.length,
    },
  });
  return row.id;
}

/**
 * Saves issues and their category details in ONE transaction, so a page never ends
 * up with half its issues. IDs are generated by us (UUIDs), which lets us insert
 * the base rows and the detail rows with fast bulk inserts (createMany).
 */
export async function saveIssues(
  prisma: PrismaClient,
  scanId: string,
  scanPageId: string | null,
  drafts: IssueDraft[],
): Promise<void> {
  if (drafts.length === 0) return;
  const json = (value: unknown) => (value ?? undefined) as Prisma.InputJsonValue | undefined;

  await prisma.$transaction([
    prisma.issue.createMany({
      data: drafts.map((d) => ({
        id: d.id,
        scanId,
        scanPageId,
        category: d.category,
        severity: d.severity,
        ruleId: d.ruleId,
        title: d.title,
        description: d.description,
        pageUrl: d.pageUrl,
        viewport: d.viewport,
        selector: d.selector,
        htmlSnippet: d.htmlSnippet,
        boundingBox: json(d.boundingBox),
        suggestedFix: d.suggestedFix,
        details: json(d.details),
        fingerprint: d.fingerprint,
        screenshotId: d.screenshotId ?? null,
        classification: classifyDraft(d),
      })),
    }),
    prisma.accessibilityIssue.createMany({
      data: drafts
        .filter((d) => d.accessibility)
        .map((d) => ({
          issueId: d.id,
          axeRuleId: d.accessibility!.axeRuleId,
          impact: d.accessibility!.impact,
          wcagCriteria: d.accessibility!.wcagCriteria,
          wcagLevel: d.accessibility!.wcagLevel,
          tags: d.accessibility!.tags,
          helpUrl: d.accessibility!.helpUrl,
          detection: d.accessibility!.detection,
          failureSummary: d.accessibility!.failureSummary,
        })),
    }),
    prisma.uIHealthIssue.createMany({
      data: drafts
        .filter((d) => d.uiHealth)
        .map((d) => ({
          issueId: d.id,
          checkType: d.uiHealth!.checkType,
          resourceUrl: d.uiHealth!.resourceUrl ?? null,
          statusCode: d.uiHealth!.statusCode ?? null,
          measurements: json(d.uiHealth!.measurements),
        })),
    }),
    prisma.functionalIssue.createMany({
      data: drafts
        .filter((d) => d.functional)
        .map((d) => ({
          issueId: d.id,
          checkType: d.functional!.checkType,
          controlName: d.functional!.controlName,
          controlRole: d.functional!.controlRole,
          controlSelector: d.functional!.controlSelector,
          interaction: json(d.functional!.interaction),
        })),
    }),
    prisma.compatibilityIssue.createMany({
      data: drafts
        .filter((d) => d.compatibility)
        .map((d) => ({
          issueId: d.id,
          browser: d.compatibility!.browser,
          browserVersion: d.compatibility!.browserVersion,
          baselineVersion: d.compatibility!.baselineVersion,
          checkType: d.compatibility!.checkType,
          matchMethod: d.compatibility!.matchMethod,
          evidence: json(d.compatibility!.evidence)!,
        })),
    }),
    prisma.sEOIssue.createMany({
      data: drafts
        .filter((d) => d.seo)
        .map((d) => ({
          issueId: d.id,
          checkType: d.seo!.checkType as SeoCheckType,
          expected: d.seo!.expected,
          actual: d.seo!.actual,
        })),
    }),
    prisma.securityIssue.createMany({
      data: drafts
        .filter((d) => d.security)
        .map((d) => ({
          issueId: d.id,
          checkType: d.security!.checkType as SecurityCheckType,
          findingLevel: d.security!.findingLevel,
          headerName: d.security!.headerName,
          observedValue: d.security!.observedValue,
          recommendedValue: d.security!.recommendedValue,
        })),
    }),
  ]);
}

/** Removes everything a previous (failed) attempt of this scan saved, so a retry starts clean. */
export async function resetScanResults(
  prisma: PrismaClient,
  storage: FileStorage,
  scanId: string,
): Promise<void> {
  await prisma.$transaction([
    prisma.issue.deleteMany({ where: { scanId } }),
    prisma.screenshot.deleteMany({ where: { scanId } }),
    prisma.scanPage.deleteMany({ where: { scanId } }),
  ]);
  await storage.removePrefix(`scans/${scanId}`);
}
